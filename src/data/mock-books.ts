export const getBooksByCategory = () => {
  const ready = mockBooks.filter((b) => b.status === "ready");
  const continueWatching = ready.filter((b) => b.progress_percent && b.progress_percent > 0);
  const fiction = ready.filter((b) => ["fiction", "fantasy", "mystery", "romance"].includes(b.genre));
  const nonFiction = ready.filter((b) => ["non-fiction", "history", "science", "biography"].includes(b.genre));
  const business = ready.filter((b) => ["business", "self-help"].includes(b.genre));

  return {
    continueWatching,
    recentlyAdded: [...ready].sort((a, b) => b.created_at.localeCompare(a.created_at)).slice(0, 6),
    fiction,
    nonFiction,
    business,
    processing: mockBooks.filter((b) => b.status === "processing"),
  };
};
